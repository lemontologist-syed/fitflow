// Builds ONE self-contained file of the Edge Function for pasting into the
// Supabase Dashboard editor (no CLI needed):
//   supabase/fitflow-function-single-file.ts
// It inlines ../_shared/*.ts in dependency order and keeps npm: imports.
import { readFileSync, writeFileSync } from "node:fs";

const order = ["zoned", "reminders", "webpush", "scheduler"].map((n) => `supabase/functions/_shared/${n}.ts`);
const entry = "supabase/functions/fitflow/index.ts";

const stripLocalImports = (src) =>
  src.replace(/^import\s+(type\s+)?\{[^}]*\}\s+from\s+"(\.\/|\.\.\/_shared\/)[^"]+";\s*$/gms, "");
const stripExports = (src) => src.replace(/^export\s+(?=(async\s+)?(function|const|interface|type|class|let)\b)/gm, "");

let out = `// FitFlow Edge Function — single-file build for the Supabase Dashboard editor.
// GENERATED by scripts/bundle-function.mjs from supabase/functions/. Do not edit by hand.
// Function name: fitflow   ·   "Verify JWT": OFF (the function checks every request itself)
`;
const entrySrc = readFileSync(entry, "utf8");
const npmImports = entrySrc.match(/^import[^;]+from\s+"npm:[^"]+";$/gm) ?? [];
out += npmImports.join("\n") + "\n";
for (const f of order) {
  out += `\n// ---- ${f.replace("supabase/functions/", "")} ----\n`;
  out += stripExports(stripLocalImports(readFileSync(f, "utf8")));
}
out += `\n// ---- fitflow/index.ts ----\n`;
out += stripLocalImports(entrySrc.replace(/^import[^;]+from\s+"npm:[^"]+";$/gm, ""));

if (/from\s+"\.\.?\//.test(out)) throw new Error("A relative import was left in the bundle");
writeFileSync("supabase/fitflow-function-single-file.ts", out);
console.log(`Wrote supabase/fitflow-function-single-file.ts (${out.length} bytes)`);
